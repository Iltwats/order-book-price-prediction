"""Offline original-graph GRU export and independent conversion/gradient audits.

This module does not relax or replace the recorded Torch/ORT FP32 parity gate.
It is excluded from the inference package and performs no optimizer updates.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import os
from pathlib import Path
import time
import uuid

import numpy as np
import onnx
from onnx import numpy_helper
import torch

from .model_io import WEIGHT_SHAPES, _read, _validate_and_extract
from .training import OnnxSequenceEncoder, StreamingGRU, load_torch_model


def _sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def _structure_hash(graph):
    clone = copy.deepcopy(graph)
    for tensor in clone.graph.initializer:
        for field in ("raw_data", "float_data", "double_data", "int32_data",
                      "int64_data", "uint64_data", "string_data"):
            tensor.ClearField(field)
    return hashlib.sha256(clone.SerializeToString(deterministic=True)).hexdigest()


def _torch_weights(model):
    if not isinstance(model, StreamingGRU) or model.hidden_size != 128 or model.head_state != "last":
        raise ValueError("original-graph export requires StreamingGRU128 with its last-state head")
    arrays = {}

    def array(parameter):
        if parameter.dtype != torch.float32:
            raise ValueError("export requires FP32 parameters without implicit precision conversion")
        result = parameter.detach().cpu().numpy().copy()
        if not np.isfinite(result).all():
            raise ValueError("export parameters must be finite")
        return result

    def zrh(parameter):
        # Inverse mapping: Torch r,z,n -> ONNX z,r,h. The swap is self-inverse.
        value = array(parameter)
        return np.concatenate((value[128:256], value[:128], value[256:]), axis=0)

    for index, layer in enumerate((model.gru0, model.gru1)):
        if (layer.num_layers != 1 or layer.bidirectional or not layer.bias or
                layer.batch_first or layer.dropout != 0 or layer.hidden_size != 128 or
                layer.input_size != (112 if index == 0 else 128)):
            raise ValueError("incompatible GRU architecture")
        arrays[f"w{index}"] = zrh(layer.weight_ih_l0)
        arrays[f"r{index}"] = zrh(layer.weight_hh_l0)
        arrays[f"b{index}"] = np.concatenate((zrh(layer.bias_ih_l0), zrh(layer.bias_hh_l0)))
    arrays["head_w"] = array(model.head.weight).T.copy()
    arrays["head_b"] = array(model.head.bias)
    for key, shape in WEIGHT_SHAPES.items():
        if arrays[key].shape != shape:
            raise ValueError(f"invalid {key} shape: expected {shape}")
    return arrays


def export_original_graph(model, source_path, destination):
    """Write all eight Torch weight tensors into a validated original graph.

    Supports changed GRU128 weights as well as a zero-update roundtrip. The
    operation rejects source aliases and unsupported constant/indirect weights;
    it never substitutes an unverified graph generated by a Torch exporter.
    """
    source, destination = Path(source_path).resolve(), Path(destination).resolve()
    if source == destination or (destination.exists() and os.path.samefile(source, destination)):
        raise ValueError("export must not overwrite the source model")
    graph = _read(source)
    _validate_and_extract(graph)
    before_structure = _structure_hash(graph)
    arrays = _torch_weights(model)
    grus = {node.input[5]: node for node in graph.graph.node if node.op_type == "GRU"}
    names = {}
    for index in range(2):
        for key, slot in ((f"w{index}", 1), (f"r{index}", 2), (f"b{index}", 3)):
            names[key] = grus[f"hidden_{index}"].input[slot]
    matmul = next(node for node in graph.graph.node if node.op_type == "MatMul")
    add = next(node for node in graph.graph.node if node.op_type == "Add")
    names.update(head_w=matmul.input[1],
                 head_b=next(name for name in add.input if name != matmul.output[0]))
    initializers = {tensor.name: tensor for tensor in graph.graph.initializer}
    if len(set(names.values())) != 8 or not set(names.values()) <= initializers.keys():
        raise ValueError("all eight weights must be distinct direct initializers")
    for key, name in names.items():
        tensor = initializers[name]
        value = arrays[key][None] if key[0] in {"w", "r", "b"} else arrays[key]
        if tuple(tensor.dims) != value.shape or tensor.data_type != onnx.TensorProto.FLOAT:
            raise ValueError(f"initializer {name} has incompatible shape or dtype")
        # Preserve TensorProto metadata as well as every graph attribute/node.
        if tensor.HasField("raw_data"):
            tensor.raw_data = np.ascontiguousarray(value, dtype="<f4").tobytes()
        else:
            del tensor.float_data[:]
            tensor.float_data.extend(value.ravel().tolist())
    onnx.checker.check_model(graph)
    exported = _validate_and_extract(graph)
    if _structure_hash(graph) != before_structure:
        raise ValueError("export changed graph structure or tensor metadata")
    if any(exported[key].tobytes() != arrays[key].tobytes() for key in arrays):
        raise ValueError("export changed parameter bits")
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.{uuid.uuid4().hex}.tmp")
    try:
        onnx.save_model(graph, str(temporary))
        os.replace(temporary, destination)
    finally:
        temporary.unlink(missing_ok=True)
    return str(destination)


def _difference(actual, expected, *, atol=0.0, rtol=0.0):
    actual, expected = np.asarray(actual), np.asarray(expected)
    if actual.shape != expected.shape:
        raise ValueError("comparison requires identical shapes")
    finite = bool(np.isfinite(actual).all() and np.isfinite(expected).all())
    if not finite:
        return {"values": int(actual.size), "finite": False,
                "violations": int(np.count_nonzero(~np.isfinite(actual) | ~np.isfinite(expected))),
                "max_absolute_error": None, "bitwise_equal": False, "passed": False}
    error = np.abs(actual - expected)
    violations = int(np.count_nonzero(error > atol + rtol * np.abs(expected)))
    bitwise = actual.dtype == expected.dtype and actual.tobytes() == expected.tobytes()
    return {"values": int(actual.size), "finite": finite, "violations": violations,
            "max_absolute_error": float(error.max(initial=0)), "bitwise_equal": bitwise,
            "passed": finite and (bitwise if atol == rtol == 0 else violations == 0)}


def audit_roundtrip(source_path, destination_dir, *, data_path, groups, manifest_path):
    """Actually compare bulk ORT predictions and every state on development groups.

    The original-graph bulk encoder already has separately recorded callback
    parity; this compares original versus roundtrip, not Torch versus ORT.
    """
    from .data import iter_sequences
    import onnxruntime as ort
    manifest = json.loads(Path(manifest_path).read_text())
    groups = [int(group) for group in groups]
    if not groups or len(groups) != len(set(groups)) or not set(groups) <= set(manifest["splits"]["dev"]):
        raise ValueError("conversion audit requires distinct development-only groups")
    if Path(data_path).resolve() != Path(manifest["datasets"]["valid"]["path"]).resolve():
        raise ValueError("conversion audit dataset must match the development manifest")
    started = time.monotonic()
    destination_dir = Path(destination_dir).resolve()
    converted = export_original_graph(load_torch_model(source_path), source_path,
                                      destination_dir / "roundtrip.onnx")
    source_graph, converted_graph = _read(source_path), _read(converted)
    reference = _validate_and_extract(source_graph)
    actual = _validate_and_extract(converted_graph)
    parameters = {key: {**_difference(actual[key], value),
                        "sha256": hashlib.sha256(value.tobytes()).hexdigest()}
                  for key, value in reference.items()}
    original = OnnxSequenceEncoder(source_path, destination_dir / "source_bulk.onnx")
    roundtrip = OnnxSequenceEncoder(converted, destination_dir / "roundtrip_bulk.onnx")
    expected_ids = {item["row_group"]: item["seq_ix"] for item in manifest["datasets"]["valid"]["groups"]}
    sequences = []
    for sequence in iter_sequences(data_path, groups):
        if sequence.seq_ix != expected_ids[sequence.row_group]:
            raise ValueError("sequence identifier differs from the frozen manifest")
        expected = original(sequence.features)
        observed = roundtrip(sequence.features)
        sequences.append({"row_group": sequence.row_group, "seq_ix": sequence.seq_ix,
                          "rows": len(sequence.features),
                          "outputs": {name: _difference(a, b) for name, a, b in
                                      zip(("h0", "h1", "prediction"), observed, expected)}})
    strict_path = Path(__file__).resolve().parents[1] / "artifacts/training_smoke/torch_strict_parity_audit.json"
    report = {"kind": "zero_update_original_graph_roundtrip", "source": str(Path(source_path).resolve()),
              "source_sha256": _sha(source_path), "roundtrip": converted,
              "roundtrip_sha256": _sha(converted), "artifact_bytes_identical": _sha(source_path) == _sha(converted),
              "structure_sha256": _structure_hash(source_graph),
              "structure_identical": _structure_hash(source_graph) == _structure_hash(converted_graph),
              "parameters": parameters, "sequences": sequences, "sequence_count": len(sequences),
              "rows": sum(item["rows"] for item in sequences), "manifest_sha256": _sha(manifest_path),
              "audit_code_sha256": _sha(__file__),
              "mode": "actual full-sequence bulk ORT comparison, all predictions and both state sequences",
              "bulk_callback_parity_basis": "original-graph OnnxSequenceEncoder; existing test_training.py and selected/parity_smoke32.json",
              "encoder_provenance": {"source": original.provenance, "roundtrip": roundtrip.provenance},
              "environment": {"torch": str(torch.__version__), "onnxruntime": ort.__version__, "threads": 1},
              "seconds": time.monotonic() - started,
              "strict_fp32_audit": {"path": str(strict_path), "sha256": _sha(strict_path) if strict_path.exists() else None,
                                    "status": "unchanged; failed Torch/ORT gate is not superseded by this audit"}}
    report["passed"] = (report["structure_identical"] and all(x["passed"] for x in parameters.values()) and
                        all(x["passed"] for seq in sequences for x in seq["outputs"].values()))
    (destination_dir / "report.json").write_text(json.dumps(report, indent=2, allow_nan=False) + "\n")
    return report


def reference_gru(x, h, weight_ih, weight_hh, bias_ih, bias_hh):
    """Independent per-gate, differentiable ONNX LBR=1 equations; Torch order.

    Inputs are time-major and h is [1,batch,H]. Separate candidate recurrent
    bias stays inside the reset multiplication. No in-place state operations.
    """
    wi, wh = weight_ih.chunk(3), weight_hh.chunk(3)
    bi, bh = bias_ih.chunk(3), bias_hh.chunk(3)
    state, outputs = h[0], []
    for row in x:
        reset = torch.sigmoid(row @ wi[0].T + bi[0] + state @ wh[0].T + bh[0])
        update = torch.sigmoid(row @ wi[1].T + bi[1] + state @ wh[1].T + bh[1])
        candidate = torch.tanh(row @ wi[2].T + bi[2] + reset * (state @ wh[2].T + bh[2]))
        state = (1 - update) * candidate + update * state
        outputs.append(state)
    return torch.stack(outputs), state[None]


def audit_fp64_gradients(seed=20260912):
    """Check equations, all input/state/parameter gradients and finite differences.

    Tiny full Jacobians cover separate biases, nonzero states, one/short unrolls
    and saturated gates. Thresholds are fixed FP64 checks, not FP32 relaxation.
    """
    cases = []
    with torch.random.fork_rng():
        torch.manual_seed(seed)
        for length, saturation in ((1, False), (5, False), (5, True)):
            layer = torch.nn.GRU(3, 2).double()
            with torch.no_grad():
                layer.bias_ih_l0[4:] = torch.tensor([0.7, -0.4], dtype=torch.float64)
                layer.bias_hh_l0[4:] = torch.tensor([-0.6, 0.9], dtype=torch.float64)
                if saturation:
                    layer.bias_ih_l0[:4] = torch.tensor([12., -12., -10., 10.], dtype=torch.float64)
            args = (torch.randn(length, 2, 3, dtype=torch.float64, requires_grad=True),
                    torch.randn(1, 2, 2, dtype=torch.float64, requires_grad=True),
                    *[parameter.detach().clone().requires_grad_() for parameter in layer.parameters()])
            names = list(dict(layer.named_parameters()))

            def native(*values):
                return torch.func.functional_call(layer, dict(zip(names, values[2:])), values[:2])

            def loss(outputs):
                flat = torch.cat([value.flatten() for value in outputs])
                return (flat * torch.linspace(-0.8, 1.2, len(flat), dtype=torch.float64)).sum()

            expected, observed = native(*args), reference_gru(*args)
            native_grads = torch.autograd.grad(loss(expected), args)
            reference_grads = torch.autograd.grad(loss(observed), args)
            forward = [_difference(a.detach().numpy(), b.detach().numpy(), atol=1e-12, rtol=1e-10)
                       for a, b in zip(observed, expected)]
            gradients = {name: _difference(a.detach().numpy(), b.detach().numpy(), atol=1e-10, rtol=1e-8)
                         for name, a, b in zip(["input", "initial_state", *names], reference_grads, native_grads)}
            finite_difference = {name: bool(torch.autograd.gradcheck(fn, args, eps=1e-6, atol=1e-6,
                                                                     rtol=1e-4, raise_exception=False))
                                 for name, fn in (("native", native), ("reference", reference_gru))}
            cases.append({"steps": length, "saturated_gates": saturation, "forward": forward,
                          "gradients": gradients, "finite_difference": finite_difference,
                          "passed": all(x["passed"] for x in [*forward, *gradients.values()]) and all(finite_difference.values())})
    return {"kind": "FP64_equation_and_gradient_audit", "seed": seed, "cases": cases,
            "audit_code_sha256": _sha(__file__), "torch": str(torch.__version__),
            "tolerances": {"forward": {"atol": 1e-12, "rtol": 1e-10},
                           "gradient": {"atol": 1e-10, "rtol": 1e-8},
                           "finite_difference": {"eps": 1e-6, "atol": 1e-6, "rtol": 1e-4}},
            "passed": all(case["passed"] for case in cases),
            "scope": "tiny nonzero-state GRUs, all input/state/parameter derivatives; no training or FP32 parity claim"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", default="artifacts/manifest.json")
    parser.add_argument("--output", default="artifacts/round2/conversion")
    args = parser.parse_args()
    manifest = json.loads(Path(args.manifest).read_text())
    output = Path(args.output)
    output.mkdir(parents=True, exist_ok=True)
    torch.set_num_threads(1)
    gradients = audit_fp64_gradients()
    (output / "fp64_gradients.json").write_text(json.dumps(gradients, indent=2, allow_nan=False) + "\n")
    reports = {}
    for name, source in (("original", "baseline/baseline.onnx"), ("correlation1024", "models/correlation1024_seed20260912/model.onnx")):
        report = audit_roundtrip(source, output / name, data_path=manifest["datasets"]["valid"]["path"],
                                 groups=manifest["splits"]["smoke"], manifest_path=args.manifest)
        reports[name] = {"passed": report["passed"], "rows": report["rows"], "seconds": report["seconds"],
                         "artifact_bytes_identical": report["artifact_bytes_identical"]}
        print(json.dumps({name: reports[name]}), flush=True)
    summary = {"fp64_gradients_passed": gradients["passed"], "roundtrips": reports,
               "passed": gradients["passed"] and all(report["passed"] for report in reports.values())}
    (output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    return 0 if summary["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
